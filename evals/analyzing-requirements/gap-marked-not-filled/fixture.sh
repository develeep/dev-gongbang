# 주문 취소 기능 기획서

작성: 커머스기획팀 / 2026-10

## 배경

고객은 주문 취소를 고객센터 전화로만 할 수 있다. 취소 문의가 월 1,200건이다.

## 기능 목록

1. 고객은 쇼핑몰 웹의 주문 상세 화면에서 '주문 취소' 버튼을 눌러 주문을 취소한다.
2. 취소는 '결제 완료'와 '상품 준비중' 상태에서만 할 수 있다. '배송중' 이후에는 버튼을 숨긴다.
3. 주문 서버 API가 취소를 처리하고 주문 상태를 '취소 완료'로 바꾼다.
4. 취소가 끝나면 주문 서버가 고객에게 취소 완료 알림톡을 보낸다.
5. 취소된 주문은 환불한다.

## 일정

- 11월 3주차 QA
- 11월 말 배포
